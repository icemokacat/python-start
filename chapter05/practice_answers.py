# ---------------------------------------------------------------------
# 문제 8. 딕셔너리 순회 - 합계와 최고점
# ---------------------------------------------------------------------
print("[문제 8]")
scores = {"Kim": 85, "Park": 92, "Lee": 78, "Choi": 90}

for name, point in scores.items():
    print(f"{name}: {point}")

total = 0
for point in scores.values():
    total += point
print(total)

best_name = ""
best_point = -1
for name, point in scores.items():
    if point > best_point:
        best_point = point
        best_name = name
print(best_name)
print()


