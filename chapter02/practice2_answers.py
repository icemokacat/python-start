# docu
# docu...
print()


# ---------------------------------------------------------------------
# 문제 8. type() 과 id()
# ---------------------------------------------------------------------
print("[문제 8]")
v = 10
print(type(v))          # <class 'int'>
v = "ten"
print(type(v))          # <class 'str'>  - 같은 이름에 다른 타입 재대입 가능(동적 타이핑)

p = 300
q = p
print(id(p) == id(q))   # True  - q 는 p 와 "같은 객체"를 가리킴
q = 400
print(id(p) == id(q))   # False - q 가 새 객체(400)를 가리키고 p 는 300 그대로
# 대입은 "값 복사"가 아니라 "같은 객체를 가리키게 함". 재대입하면 그 이름만 옮겨감.
