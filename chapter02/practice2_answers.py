# ---------------------------------------------------------------------
# 문제 2. 같은 결과, 세 가지 방식
# ---------------------------------------------------------------------
print("[문제 2]")
name, score = "Kim", 92
print("%s : %d점" % (name, score))          # % 연산자
print("{} : {}점".format(name, score))       # str.format()
print(f"{name} : {score}점")                 # f-string
# 셋 다 동일:  Kim : 92점
print()


# ---------------------------------------------------------------------
# 문제 3. % 포매팅 - 진행률
