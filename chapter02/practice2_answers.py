# ---------------------------------------------------------------------
# 문제 6. 정렬된 표 (print 3번)
# ---------------------------------------------------------------------
print("[문제 6]")
r1 = ("ID", "NAME", "AGE")
r2 = ("1", "Ann", "30")
r3 = ("2", "Bob", "5")
row = "{:<6}{:<8}{:>4}"
print(row.format(r1[0], r1[1], r1[2]))
print(row.format(r2[0], r2[1], r2[2]))
print(row.format(r3[0], r3[1], r3[2]))
#  <6 왼쪽정렬 6칸, <8 왼쪽정렬 8칸, >4 오른쪽정렬 4칸
# 출력:
# ID    NAME     AGE
# 1     Ann       30
# 2     Bob        5
print()


# ---------------------------------------------------------------------
# 문제 7. 문자열 절삭
