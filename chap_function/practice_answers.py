# 문제 4. *args - 넘어온 모든 값의 합
# ---------------------------------------------------------------------
print("[문제 4]")


def total(*args):
    s = 0
    for n in args:      # args 는 튜플. 인자가 없으면 빈 튜플이라 for 를 안 돈다
        s += n
    return s


print(total(1, 2, 3))          # 6
print(total(10, 20, 30, 40))   # 100
print(total())                 # 0
print()


# ---------------------------------------------------------------------
# 문제 5. *args - 평균 (빈 인자 방어)
# ---------------------------------------------------------------------
print("[문제 5]")


def average(*args):
    if not args:        # 빈 튜플은 거짓 -> 0 으로 나누는 것을 막는다
        return 0
    s = 0
    for n in args:
        s += n
    return s / len(args)


print(average(10, 20, 30))   # 60 / 3 = 20.0  (나눗셈 결과는 float)
print(average(4, 5))         # 9 / 2 = 4.5
print(average())             # 0
print()


