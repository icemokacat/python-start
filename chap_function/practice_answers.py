# 문제 12. 함수 안에서 for + if + 다중 반환, f-string 으로 조립
# ---------------------------------------------------------------------
print("[문제 12]")


def count_even_odd(numbers):
    even = 0
    odd = 0
    for n in numbers:
        if n % 2 == 0:
            even += 1
        else:
            odd += 1
    return even, odd


e, o = count_even_odd([1, 2, 3, 4, 5, 6, 7])
print(f"짝수 {e}개, 홀수 {o}개")   # 짝수 3개, 홀수 4개
