# 문제 6. **kwargs - 키=값 한 줄씩 출력
# ---------------------------------------------------------------------
print("[문제 6]")


def show_profile(**kwargs):
    for key in kwargs:              # kwargs 는 딕셔너리. key 를 순회
        print(f"{key} = {kwargs[key]}")


show_profile(name="Lee", age=20)
# name = Lee
# age = 20   (딕셔너리는 넣은 순서를 유지한다)
print()


