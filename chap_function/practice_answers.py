def describe(title, *items, **options):
    print("title:", title)      # 첫 위치 인자
    print("items:", items)      # 나머지 위치 인자들 -> 튜플
    print("options:", options)  # 키워드 인자들 -> 딕셔너리


describe("cart", "apple", "milk", coupon=True, point=500)
# title: cart
# items: ('apple', 'milk')
# options: {'coupon': True, 'point': 500}
print()


