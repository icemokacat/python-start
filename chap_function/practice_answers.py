# 문제 3. 다중 반환 + 언패킹
# ---------------------------------------------------------------------
print("[문제 3]")


def min_max(numbers):
    smallest = numbers[0]
    largest = numbers[0]
    for n in numbers:
        if n < smallest:
            smallest = n
        if n > largest:
            largest = n
    return smallest, largest   # 콤마로 여러 값을 return -> 튜플로 묶여 나감


numbers = [3, 9, 1, 7, 5]
lo, hi = min_max(numbers)     # 튜플을 두 변수로 언패킹
print(lo, hi)                 # 1 9
print(min_max(numbers))       # (1, 9)  - 그대로 받으면 튜플
print()


