# 예제4
class Dog2:
    # 클래스 속성
    species = 'firstdog'
    
    # 초기화/인스턴스 속성
    def __init__(self, name, age):
        self.name = name
        self.age = age
        
    def info(self):
        return '{} is {} years old'.format(self.name, self.age)
    
    def speak(self, sound):
        return "{} says {}!".format(self.name, sound)    
    
# 인스턴스 속성
c = Dog2('july',4)
d = Dog2('Marry', 10)
print(c.info())
# 메소드 호출
print(c.speak('wal wal'))
print(d.speak('Mung Mung'))
