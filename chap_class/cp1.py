SelfTest.func2(f)


# =============================================================================
# [정리] f.func1() 은 왜 에러나고, SelfTest.func1() 은 왜 되는가? (Java 와 비교)
# =============================================================================
#
# -----------------------------------------------------------------------------
# 1. 파이썬에서 "메소드"의 실체
# -----------------------------------------------------------------------------
# 파이썬에서 클래스 안에 def 로 정의한 것은 사실 그냥 "함수(function)" 이고,
# 클래스의 속성(attribute)으로 저장돼 있을 뿐이다.
# Java 처럼 "인스턴스 메소드 / static 메소드" 를 선언 단계에서 키워드로
# 구분하지 않는다. 구분은 "어떻게 호출(접근)되느냐" 로 런타임에 결정된다.
#
# 핵심 규칙 (디스크립터 프로토콜, function.__get__):
#   - 인스턴스로 접근하면  ( f.func1 )  -> "bound method" 가 만들어지고
#     첫 번째 인자로 그 인스턴스(f)가 자동으로 채워진다.
#   - 클래스로 접근하면    ( SelfTest.func1 ) -> 그냥 원본 함수 그대로.
#     아무것도 자동으로 안 넣어준다. (Python 3 기준)
#
# -----------------------------------------------------------------------------
# 2. f.func1() 이 에러나는 이유
# -----------------------------------------------------------------------------
#   f.func1()  ==  SelfTest.func1(f)   <- 파이썬이 f 를 첫 인자로 몰래 넣음
#
# 그런데 func1 은  def func1():  즉 파라미터가 0개다.
# 인자 1개(f)를 받았으니:
#   TypeError: func1() takes 0 positional arguments but 1 was given
# (버전에 따라 문구는 조금 다름. 요지는 "0개 받는데 1개 들어왔다")
#
# 반대로 func2 는  def func2(self):  이므로 self 자리에 f 가 들어가서 정상 동작.
#   f.func2()  ==  SelfTest.func2(f)   -> OK
#
# -----------------------------------------------------------------------------
# 3. SelfTest.func1() 이 되는 이유
# -----------------------------------------------------------------------------
# 클래스로 직접 접근하면 인스턴스를 끼워넣지 않는다.
#   SelfTest.func1()  -> 인자 0개로 호출 -> func1 시그니처(0개)와 일치 -> OK
#
# 참고: SelfTest.func2() 는 반대로 에러난다.
#   TypeError: func2() missing 1 required positional argument: 'self'
#   -> SelfTest.func2(f) 처럼 self 를 직접 넘겨야 동작.
#
# -----------------------------------------------------------------------------
# 4. Java 와 비교
# -----------------------------------------------------------------------------
# [Java]
#   class SelfTest {
#       static void func1() { ... }   // static: 인스턴스 필요 없음
#       void func2() { ... }          // 인스턴스 메소드, this 는 컴파일러가 주입
#   }
#   - 선언부의 'static' 키워드로 종류가 "고정"된다.
#   - this 는 예약어이며, 파라미터 목록에 절대 쓰지 않는다. JVM/컴파일러가
#     자동으로 넘겨주는 "숨겨진 인자" 다. 개발자 눈에 안 보인다.
#   - f.func1() 도 되고 SelfTest.func1() 도 된다 (static 이라서. 단 인스턴스로
#     호출하면 IDE 가 경고). 인스턴스 메소드 func2() 는 인스턴스 없이는 호출 불가.
#   - 즉 Java 는 "호출 형태가 무엇이든 메소드 종류는 선언 때 이미 정해져 있다".
#
# [Python]
#   - func1, func2 둘 다 "선언상으로는" 그냥 함수다. static 이라고 말한 적 없다.
#   - self 를 쓸지 말지는 개발자가 파라미터로 직접 적는다. 언어가 강제 안 함.
#   - 인스턴스로 호출하느냐(SelfTest 로 호출하느냐)에 따라 self 주입 여부가
#     런타임에 갈린다. 그래서 func1 은 "클래스로 부르면 되고 인스턴스로 부르면
#     터지는" 어정쩡한 상태가 된다.
#   - Java 의 static 메소드에 대응하려면 명시적으로 데코레이터를 붙여야 한다:
#
#         class SelfTest:
#             @staticmethod
#             def func1():
#                 print('Func1 called')
#
#     이렇게 하면 디스크립터가 인스턴스를 주입하지 않으므로
#     f.func1() 과 SelfTest.func1() 둘 다 정상 동작한다. (Java 와 동일한 느낌)
#
# -----------------------------------------------------------------------------
# 5. self 는 Java 의 this 와 같은 것인가?
# -----------------------------------------------------------------------------
# "현재 인스턴스를 가리키는 참조" 라는 개념적 역할은 this 와 같다.
# 하지만 성격은 다르다:
#
#   (1) self 는 예약어가 아니다. 단지 관례(convention)일 뿐인 "변수 이름".
#       def func2(this):  또는  def func2(x):  라고 써도 문법상 동작한다.
#       (다들 self 로 쓰기로 약속했을 뿐. Java 의 this 는 바꿀 수 없는 예약어)
#
#   (2) self 는 "명시적"이다. 메소드 정의의 첫 번째 파라미터로 반드시 적어야 하고,
#       호출 시에도 (내부적으로) 명시적으로 전달된다.
#       - "Explicit is better than implicit" (파이썬 철학)
#       - SelfTest.func2(f) 처럼 눈에 보이게 넘길 수도 있다.
#       Java 의 this 는 "암묵적"이다. 선언도 안 하고 전달도 안 보인다.
#
#   (3) self 가 채워지는 메커니즘은 "디스크립터 + bound method" 다.
#       f.func2 를 평가하는 순간 function.__get__(f, SelfTest) 가 호출돼
#       f 가 미리 바인딩된 bound method 객체가 만들어진다.
#       f.func2()  ->  (bound method).__call__()  ->  원본함수(f) 실행
#
#   (4) 그래서 파이썬에서는 self 를 "가지고 놀 수" 있다.
#       - 언바운드로 직접 호출: SelfTest.func2(f)
#       - 메소드를 변수에 담기: m = f.func2 ; m()  (f 가 이미 묶여 있음)
#       - 다른 객체에 함수 재할당 등
#
# 요약:
#   self ~= this (역할은 비슷)
#   그러나 self = "관례상의 이름 + 명시적으로 선언/전달되는 첫 번째 인자"
#          this = "언어가 강제하는 예약어 + 암묵적으로 주입되는 숨은 참조"
#
# -----------------------------------------------------------------------------
# 6. print(id(self)) 는 무엇?
# -----------------------------------------------------------------------------
# id(self) 는 인스턴스의 고유 식별값(CPython 에서는 메모리 주소).
# f.func2() 안에서 self 는 곧 f 이므로  id(self) == id(f)  가 출력된다.
# (Java 로 치면 System.identityHashCode(this) 가 객체의 것과 같은 것과 유사)

# 예제3
# 클래스 변수, 인스턴스 변수
class Warehouse:
    # 클래스 변수 = 0
    stock_num = 0 # 재고
    
    def __init__(self, name):
        # 인스턴스 변수
        self.name = name 
        Warehouse.stock_num += 1
        
    # 객체가 소멸할때 자동으로 호출됨    
    def __del__(self):
        Warehouse.stock_num -= 1

user1 = Warehouse('Lee')
user2 = Warehouse('Cho')

print(Warehouse.stock_num)
Warehouse.stock_num += 10
print(Warehouse.stock_num)
# => 2  (user1, user2 두 번 생성돼서 stock_num 이 2)


# =============================================================================
# [정리] stock_num 은 왜 "공유" 되는가? (클래스 변수 vs 인스턴스 변수)
# =============================================================================
#
# -----------------------------------------------------------------------------
# 0. 먼저 오해 방지: 인스턴스는 파이썬도 "각자 별도 공간" 이다 (Java 와 동일)
# -----------------------------------------------------------------------------
# Java 에서:
#     a = new Car();
#     b = new Car();
#   -> 힙에 Car 객체 2개가 따로 만들어지고, a / b 는 각 객체의 "주소(참조)" 를
#      들고 있다. a 와 b 는 완전히 별개 공간이다.
#
# 파이썬도 똑같다. 하나도 안 다르다.
#     a = Car()
#     b = Car()
#     print(id(a), id(b))   # 서로 다른 주소값
#     print(a is b)         # False  (다른 객체)
#   -> a, b 는 힙에 있는 서로 다른 객체를 가리키는 참조이고,
#      각 객체는 자기만의 __dict__(개인 공간) 를 갖는다.
#      self.name = ... 하면 그 객체 공간에만 저장된다. => Java 와 동일.
#
# 그럼 뭐가 "공유" 였나?  ->  클래스 변수 stock_num 딱 하나.
# 이유: stock_num 은 a 나 b 안에 있는 게 아니라, 제3의 객체인
#       "Warehouse 클래스 객체" 위에 산다. 클래스 객체는 프로그램에 1개뿐이라
#       모두가 같은 걸 본다.
# 이것도 Java 와 같은 개념이다:  Java 의 'static int stockNum' 도
#       a / b 가 아니라 클래스(메서드 영역)에 딱 1개 존재한다.
#
#   메모리 그림:
#
#       ┌───────────────────────┐
#       │ Warehouse 클래스 객체    │  <- 프로그램에 딱 1개
#       │   stock_num = 2        │  <- 공유되는 건 이것뿐
#       │   __init__ / __del__   │
#       └───────────────────────┘
#             ▲            ▲
#             │            │  ("내 클래스는 Warehouse" 라고 둘 다 가리킴)
#       ┌───────────┐  ┌───────────┐
#       │ 인스턴스 #1 │  │ 인스턴스 #2 │  <- 서로 다른 주소, 각자 공간 (Java 와 동일)
#       │ name='Lee'│  │ name='Cho'│
#       └───────────┘  └───────────┘
#             ▲              ▲
#           user1          user2       <- 각 객체를 가리키는 참조
#
#   표로 대응:
#       Java 'String name;'        == Python 'self.name = ...'     (인스턴스마다 개별)
#       Java 'static int stockNum' == Python class 본문 'stock_num = 0' (클래스에 1개, 공유)
#
# -----------------------------------------------------------------------------
# 1. 직관적인 그림: "공용 화이트보드" vs "개인 사물함"
# -----------------------------------------------------------------------------
# (주의: 아래 교실/학생 비유는 "변수가 어느 몸통에 저장되느냐" 를 설명하는 것이지,
#  인스턴스가 별도 객체가 아니라는 뜻이 절대 아니다. 인스턴스는 0번 항목대로
#  각자 독립된 객체다.)
#
# 한국 블로그/강의에서 자주 쓰는 비유로 보면 이해가 쉽다.
#
#   - 클래스 객체        = 교실 앞 게시판이 걸린 "교탁" 하나
#   - 인스턴스(user1..) = 각자 자기 책상과 사물함을 가진 학생 (별개 존재)
#
#   - 클래스 변수(stock_num) = 교탁 위에 놓인 "공용 화이트보드" 1개
#       * 반에 딱 하나뿐이다.
#       * 학생 누가 와서 숫자를 고쳐도 모두가 같은 보드를 본다.
#       * 그래서 user1 이 만들어질 때 +1, user2 가 만들어질 때 +1 하면
#         보드에는 2 가 적혀 있고, 누가 봐도 2 다. => "공유"
#
#   - 인스턴스 변수(self.name) = 학생마다 하나씩 있는 "개인 사물함 이름표"
#       * user1 사물함엔 'Lee', user2 사물함엔 'Cho'.
#       * 서로 아무 상관 없다. => "공유 안 됨"
#
# 왜 이렇게 갈리냐? 파이썬에선 클래스도, 인스턴스도 각자
# "이름표를 붙여 물건을 넣어두는 서랍(__dict__, 네임스페이스)" 을 하나씩 갖는다.
# 변수가 "어느 서랍에 들어갔는지" 가 곧 공유 여부다.
#
#     class 본문에 그냥      stock_num = 0   -> "교실 서랍(클래스)" 에 들어감  -> 공용 보드
#     메소드 안에서 self. 붙여 self.name = .. -> "그 학생 서랍(인스턴스)" 에 들어감 -> 개인 이름표
#
# 즉 "self 를 붙였냐 / class 본문에 바로 썼냐" 라는 위치 하나로 결정된다.
# (다른 언어처럼 static 같은 키워드로 선언하는 게 아니다. 위치가 곧 선언이다.)
#
#   확인해보기:
#     print(Warehouse.__dict__)   # 여기에 stock_num 이 보임 (교실 서랍)
#     print(user1.__dict__)       # {'name': 'Lee'} 만 보임 (개인 서랍)
#     print(user2.__dict__)       # {'name': 'Cho'}
#
# -----------------------------------------------------------------------------
# 2. 읽을 땐 "내 서랍 -> 교실 서랍" 순서로 찾는다 (그래서 공유처럼 보인다)
# -----------------------------------------------------------------------------
# user1.stock_num 이라고 쓰면 파이썬은:
#   (1) 먼저 user1 개인 서랍(__dict__)을 뒤진다  -> stock_num 없음
#   (2) 없으면 교실 서랍(클래스 __dict__)을 뒤진다 -> 여기서 찾음! -> 공용 보드값
#   (3) 그래도 없으면 부모 클래스 서랍으로 올라간다
#
# 그래서 user1.stock_num 도 user2.stock_num 도 결국 같은 "공용 보드"를 읽는다.
# 값이 하나로 보이는 이유가 이것이다.
#
# -----------------------------------------------------------------------------
# 3. 함정: 인스턴스로 "대입" 하면 공유가 끊긴다 (shadowing)
# -----------------------------------------------------------------------------
# 읽기는 교실 서랍까지 올라가지만, "쓰기(대입)" 는 항상 자기 서랍에 한다.
#
#   user1.stock_num = 100      # user1 개인 서랍에 stock_num=100 이라는
#                              # "새 이름표" 를 만들어 붙임 (공용 보드는 안 건드림)
#   print(user1.stock_num)     # 100  <- 이제 자기 서랍부터 찾으니 자기 값
#   print(user2.stock_num)     # 2    <- 얜 여전히 공용 보드를 봄
#   print(Warehouse.stock_num) # 2    <- 공용 보드는 그대로
#
# 이 함정 때문에 이 예제는 __init__ / __del__ 안에서
#       self.stock_num += 1     (X)  <- 읽을 땐 공용값, 쓸 땐 개인 서랍에 새로 만듦
#   가 아니라
#       Warehouse.stock_num += 1 (O)  <- 공용 보드를 콕 집어서 고침
#   이라고 "클래스 이름" 으로 명시한 것이다.
#
# -----------------------------------------------------------------------------
# 4. 생성 매커니즘 (간략)
# -----------------------------------------------------------------------------
#
#   [Q] "Warehouse 클래스 객체" 는 최초로 인스턴스를 한 번 만들어야 생기나,
#       아니면 class 를 선언(define)한 시점에 생기나?
#   [A] class 를 "선언한 시점" 에 생긴다. 인스턴스 생성과는 무관하다.
#
#   (0) 클래스 객체가 만들어지는 시점 = class 문이 "실행" 되는 순간
#       파이썬에서 'class Warehouse:' 는 def 처럼 그냥 실행되는 문장이다.
#       인터프리터가 이 줄에 도달하면 바로 그 자리에서:
#         a. 클래스 본문(stock_num=0, __init__, __del__)을 새 네임스페이스에서
#            위에서 아래로 딱 1번 실행
#         b. 메타클래스 type 을 호출해 그 네임스페이스로 "클래스 객체" 를 생성
#         c. 그 객체를 이름 Warehouse 에 바인딩
#       => 이때 stock_num = 0 도 딱 한 번 실행된다. 인스턴스가 0개여도
#          Warehouse.stock_num 은 이미 접근 가능하다.
#
#       확인:
#         print("A")
#         class Warehouse:
#             print("클래스 본문 실행됨")   # 인스턴스 없이도 여기서 출력됨
#             stock_num = 0
#         print("B")
#         # 출력 순서:  A -> 클래스 본문 실행됨 -> B
#
#       (참고) class 문이 함수 안에 있으면 그 함수가 불릴 때마다 새 클래스
#              객체가 생긴다. 모듈 최상단에 있으면 모듈이 처음 로드될 때 1번.
#
#       [Java 와 차이] Java 는 "지연(lazy)": 클래스로더가 최초 사용 시점
#         (첫 new, 첫 static 접근 등)에 클래스를 로드하고 static 초기화를 돌린다.
#       파이썬은 "즉시(eager)": class 문을 지나가는 순간 이미 완성되어 있다.
#
#   그 다음, user1 = Warehouse('Lee')  가 실행되면:
#
#   (1) (클래스 객체는 이미 0번에서 만들어져 있음. 여기서 새로 안 만든다.)
#       Warehouse 클래스 객체의 서랍(__dict__)에는 이미
#       stock_num, __init__, __del__ 이 들어 있는 상태.
#
#   (2) Warehouse('Lee') 호출 -> 내부적으로 순서대로:
#         a. __new__  : 빈 인스턴스(내용 없는 학생 껍데기) 를 만든다
#         b. __init__ : 그 껍데기를 self 로 받아 초기화
#              self.name = 'Lee'          # 이 학생 개인 서랍에 이름표
#              Warehouse.stock_num += 1   # 공용 보드 +1
#         c. 완성된 인스턴스를 돌려줌 -> user1 이라는 이름에 묶임(바인딩)
#
#   (3) user2 = Warehouse('Cho') 도 똑같이 진행 -> 공용 보드 다시 +1 -> 2
#
#   (4) __del__ 은 그 인스턴스를 아무도 안 쓰게 될 때(참조 0, 가비지 컬렉션)
#       파이썬이 자동 호출한다. 프로그램 끝에서 user1, user2 가 정리되면
#       각각 stock_num -= 1 이 돌아 최종 0 으로 복귀.
#       (단, "정확히 언제" 호출되는지는 파이썬이 알아서 하므로 보장되지 않는다.)
#
# -----------------------------------------------------------------------------
# 한 줄 요약
# -----------------------------------------------------------------------------
#   인스턴스(user1, user2)는 파이썬도 Java 처럼 "각자 다른 객체 / 다른 주소".
#   공유되는 건 클래스 객체에 얹힌 클래스 변수 1개뿐. (Java 의 static 과 같은 개념)
