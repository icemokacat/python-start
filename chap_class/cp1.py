# 예제1
class Dog:
    # 클래스 속성
    species = 'firstdog'
    
    # 초기화/인스턴스 속성
    def __init__(self, name, age):
        self.name = name
        self.age = age
    
print(type(Dog))
# => <class 'type'>
print(Dog)
# => <class '__main__.Dog'>

# 인스턴스화
a = Dog("mikky",2)
b = Dog("baby", 3)

# 비교
print(a == b, id(a), id(b))
# ==> false

print()
# 네임스페이스
print('dog1', a.__dict__)
print('dog2', b.__dict__)

# 인스턴스 속성 확인
print('{} is {} and {} is {}'.format(a.name, a.age, b.name, b.age))

if a.species == 'firstdog':
    print('{0} is a {1}'.format(a.name, a.species))
    
print(Dog.species)
print(a.species)

