# 문제 9. 딕셔너리 - get 기본값 / 추가 / in
# ---------------------------------------------------------------------
print("[문제 9]")
item = {"name": "mouse", "price": 15000}
print(item.get("stock", 0))   # 0 - 키가 없으면 두 번째 인자를 반환 (KeyError 아님)
item["stock"] = 10            # 새 키 추가
print("stock" in item)        # True
print(item.get("stock", 0))   # 10 - 이제 키가 있으므로 실제 값
print()


# ---------------------------------------------------------------------
# 문제 10. 딕셔너리 - keys / values / pop / update
# ---------------------------------------------------------------------
print("[문제 10]")
d = {"a": 1, "b": 2, "c": 3}
print(list(d.keys()))     # ['a', 'b', 'c']
print(list(d.values()))   # [1, 2, 3]
print(d.pop("b"))         # 2 - 해당 키를 지우고 값을 반환
print(d)                  # {'a': 1, 'c': 3}
d.update(a=100, z=9)      # 있는 키는 수정, 없는 키는 추가
print(d)                  # {'a': 100, 'c': 3, 'z': 9}
print()


