# 문제 11. 셋(set) - 중복 제거 / add / 집합 연산
# ---------------------------------------------------------------------
print("[문제 11]")
raw = [1, 1, 2, 2, 3]
s = set(raw)
print(len(s))                       # 3 - 중복 제거
s.add(3)                            # 이미 있음 -> 변화 없음
s.add(4)
print(sorted(s))                    # [1, 2, 3, 4] - set 은 순서가 없어 sorted 로 정렬
print(sorted({1, 2, 3, 4} & {3, 4, 5}))  # 교집합 -> [3, 4]
print(sorted({1, 2, 3, 4} - {3, 4, 5}))  # 차집합 -> [1, 2]
