# 문제 1. 자료형 확인 - type()
# ---------------------------------------------------------------------
print("[문제 1]")
s1 = (10, 20)
s2 = [10, 20]
s3 = {10, 20}
s4 = {"a": 1}
s5 = 3 + 4j
s6 = (10 == 10)
print(type(s1))   # <class 'tuple'>   - 소괄호 + 콤마 => 튜플
print(type(s2))   # <class 'list'>    - 대괄호 => 리스트
print(type(s3))   # <class 'set'>     - 중괄호 + 콤마(키:값 아님) => 셋
print(type(s4))   # <class 'dict'>    - 중괄호 + 키:값 => 딕셔너리
print(type(s5))   # <class 'complex'> - j 가 붙으면 복소수
print(type(s6))   # <class 'bool'>    - 비교 연산 결과는 True/False
print()


