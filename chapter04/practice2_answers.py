# ---------------------------------------------------------------------
# 문제 6. 참조(alias) vs 복사(copy) 와 id()
# ---------------------------------------------------------------------
print("[문제 6]")
origin = [1, 2, 3]
alias = origin
alias.append(4)
print(origin)                    # [1, 2, 3, 4] - alias 와 origin 은 같은 객체
print(id(origin) == id(alias))   # True

clone = origin.copy()            # <-- copy() 로 얕은 복사 (다른 객체)
clone.append(99)
print(origin)                    # [1, 2, 3, 4] - 99 는 clone 에만
# 대입(=)은 같은 객체를 가리키게 할 뿐, 복사가 아니다. copy() 로 새 리스트를 만든다.
print()


